#ifndef BOT_SHIELD_PROXY_HTTP_MESSAGE_H_
#define BOT_SHIELD_PROXY_HTTP_MESSAGE_H_

#include <asio/ip/address.hpp>
#include <cstdint>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace bot_shield {

// Header fields with lowercase names, in order.
using HeaderList = std::vector<std::pair<std::string, std::string>>;

// A request in protocol-neutral (HTTP/2-style) form, as sent to Traefik.
struct ProxyRequest {
  std::string method;
  std::string scheme = "https";
  std::string authority;
  std::string path;
  HeaderList headers;
};

struct ProxyResponse {
  int status = 0;
  HeaderList headers;
};

// Who the request came from, for the forwarding headers.
struct ClientInfo {
  asio::ip::address address;
  uint16_t local_port = 443;
  // SNI of the client connection; the upstream pool is keyed by it.
  std::string server_name;
};

// Connection-specific (hop-by-hop) header that must not be forwarded.
bool IsHopByHop(std::string_view lowercase_name);

// Headers a client could use to spoof its address or our verdicts.
bool IsSpoofableForwardingHeader(std::string_view lowercase_name);

// Drops hop-by-hop headers (including names listed in Connection), Host,
// spoofable forwarding headers and X-Bot-*. "te: trailers" survives.
HeaderList FilterRequestHeaders(const HeaderList& headers);

// Drops headers that are illegal in HTTP/2 responses.
HeaderList FilterResponseHeaders(const HeaderList& headers);

// Appends X-Forwarded-For/-Proto/-Host/-Port and X-Real-IP for Traefik
// (which trusts them from the gateway's address only).
void AddForwardingHeaders(const ClientInfo& client, std::string_view authority,
                          HeaderList* headers);

// First value of a header, or "".
std::string_view FindHeader(const HeaderList& headers, std::string_view name);

// Whether a response to `method` with `status` carries a body.
bool ResponseHasBody(std::string_view method, int status);

std::string_view ReasonPhrase(int status);

// "HTTP/<version> <status> <reason>\r\n" + headers + "\r\n".
std::string FormatH1ResponseHead(std::string_view version, int status,
                                 const HeaderList& headers);

// A small text/plain response generated by the gateway itself.
ProxyResponse LocalResponse(int status, std::size_t body_size);

}  // namespace bot_shield

#endif  // BOT_SHIELD_PROXY_HTTP_MESSAGE_H_
