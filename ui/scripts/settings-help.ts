// Field help for the settings screen, from the comments of the documented
// configuration (deploy/bot-shield.yaml): a comment block right above a key
// (or a section) and a comment at the end of its line. Commented examples
// right after a key ("# nats: ...", "#  - name: ...") are left out; a
// commented section ("# throttle:") takes the block above it.

const KEY = /^( *)([a-z_][a-z0-9_]*):(.*)$/;
const COMMENTED_SECTION = /^# ([a-z_][a-z0-9_]*):\s*$/;
const EXAMPLE = /^\s*#\s*(- |[A-Za-z0-9_.*"-]+:(\s|$))/;

// The comment at the end of a value, outside quotes.
function trailingComment(rest: string): string {
  let quote = '';
  for (let i = 0; i < rest.length; i += 1) {
    const ch = rest[i];
    if (quote) {
      if (ch === quote) quote = '';
    } else if (ch === '"' || ch === "'") {
      quote = ch;
    } else if (ch === '#' && (i === 0 || rest[i - 1] === ' ')) {
      return rest.slice(i + 1).trim();
    }
  }
  return '';
}

export function extractSettingsHelp(yaml: string): Record<string, string> {
  const help: Record<string, string> = {};
  const stack: { indent: number; key: string }[] = [];
  let block: string[] = [];
  // After a key line: example lines are skipped until something else.
  let afterKey = false;
  let inExample = false;
  for (const line of yaml.split('\n')) {
    if (line.trim() === '') {
      block = [];
      afterKey = false;
      inExample = false;
      continue;
    }
    if (inExample) continue;
    const section = COMMENTED_SECTION.exec(line);
    if (section?.[1]) {
      if (block.length) help[section[1]] = block.join(' ');
      block = [];
      inExample = true;
      continue;
    }
    if (line.trimStart().startsWith('#')) {
      if (afterKey && EXAMPLE.test(line)) continue;
      afterKey = false;
      block.push(line.trimStart().replace(/^#\s?/, '').trim());
      continue;
    }
    const match = KEY.exec(line);
    if (!match) {
      block = [];
      continue;
    }
    const indent = match[1]?.length ?? 0;
    const name = match[2] ?? '';
    while (stack.length && (stack.at(-1)?.indent ?? 0) >= indent) stack.pop();
    const path = [...stack.map((item) => item.key), name].join('.');
    const text = [...block, trailingComment(match[3] ?? '')]
      .filter(Boolean)
      .join(' ');
    if (text) help[path] = text;
    stack.push({ indent, key: name });
    block = [];
    afterKey = true;
  }
  return help;
}

// The help of `path`, else of the nearest section above it.
export function helpFor(
  help: Record<string, string>,
  path: string,
): string | undefined {
  const parts = path.split('.');
  while (parts.length) {
    const text = help[parts.join('.')];
    if (text) return text;
    parts.pop();
  }
  return undefined;
}

export function renderSettingsHelp(help: Record<string, string>): string {
  const lines = Object.keys(help)
    .sort()
    .map((path) => `  ${JSON.stringify(path)}: ${JSON.stringify(help[path])},`);
  return [
    '// Generated by `npm run settings-help` from deploy/bot-shield.yaml: the',
    '// comments above each key. Do not edit; edit that file and regenerate.',
    '',
    'export const SETTINGS_HELP: Readonly<Record<string, string>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}
