#!/usr/bin/env python3
"""Turns the XDP object (clang -target bpfel) into C++ source.

Writes the instructions of the "xdp" section and its map relocations (the
ld_imm64 instructions the loader patches with map file descriptors), so the
gateway loads the program without libbpf or libelf:

    tools/bpf_embed.py filter.bpf.o xdp_program.cc
"""

import struct
import sys


def sections(elf):
    if elf[:4] != b"\x7fELF" or elf[4] != 2 or elf[5] != 1:
        sys.exit("expected a little-endian ELF64 object")
    shoff, = struct.unpack_from("<Q", elf, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    headers = []
    for i in range(shnum):
        name, kind, _flags, _addr, offset, size, link, info, _align, entsize = (
            struct.unpack_from("<IIQQQQIIQQ", elf, shoff + i * shentsize))
        headers.append(dict(name=name, kind=kind, offset=offset, size=size,
                            link=link, info=info, entsize=entsize))
    names = headers[shstrndx]

    def name_of(offset, table):
        start = table["offset"] + offset
        return elf[start:elf.index(b"\0", start)].decode()

    for header in headers:
        header["label"] = name_of(header["name"], names)
    return headers, name_of


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    elf = open(sys.argv[1], "rb").read()
    headers, name_of = sections(elf)
    by_label = {h["label"]: (i, h) for i, h in enumerate(headers)}
    if "xdp" not in by_label:
        sys.exit("no xdp section")
    xdp_index, xdp = by_label["xdp"]
    code = elf[xdp["offset"]:xdp["offset"] + xdp["size"]]
    relocations = []
    for header in headers:
        if header["kind"] != 9 or header["info"] != xdp_index:  # SHT_REL
            continue
        symtab = headers[header["link"]]
        strtab = headers[symtab["link"]]
        for at in range(header["offset"], header["offset"] + header["size"],
                        16):
            offset, info = struct.unpack_from("<QQ", elf, at)
            symbol = info >> 32
            sym_name, = struct.unpack_from(
                "<I", elf, symtab["offset"] + symbol * symtab["entsize"])
            name = name_of(sym_name, strtab)
            if offset % 8:
                sys.exit("misaligned relocation")
            relocations.append((offset // 8, name))

    lines = [
        "// Generated by tools/bpf_embed.py from src/xdp/filter.bpf.c.",
        "// Do not edit.",
        '#include "xdp/xdp_program.h"',
        "",
        "#include <cstddef>",
        "",
        "namespace bot_shield {",
        "",
        "const unsigned char kXdpProgram[] = {",
    ]
    for start in range(0, len(code), 12):
        chunk = code[start:start + 12]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines += [
        "};",
        f"const std::size_t kXdpProgramSize = {len(code)};",
        "",
        "const XdpRelocation kXdpRelocations[] = {",
    ]
    lines += [f'    {{{index}, "{name}"}},' for index, name in relocations]
    lines += [
        "};",
        f"const std::size_t kXdpRelocationCount = {len(relocations)};",
        "",
        "}  // namespace bot_shield",
        "",
    ]
    with open(sys.argv[2], "w") as out:
        out.write("\n".join(lines))


if __name__ == "__main__":
    main()
